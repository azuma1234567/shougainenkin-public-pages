- ア……現在の病状または状態像(該当する項目に丸をつける)
- イ……その状態の具体的な記載
- ウ……日常生活状況。ここに**「日常生活能力の判定」7項目**と**「日常生活能力の程度」5段階**が入る
- エ……現症時の就労状況
