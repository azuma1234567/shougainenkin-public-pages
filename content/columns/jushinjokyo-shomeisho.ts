理由は単純で、この書類だけは**過去の病院**に頼まなければならないから。もう通っていない、担当医の顔も覚えていない、そもそも診察券をなくした——そんな病院に電話をかける作業は、心理的なハードルが高い。だから後回しになり、そして後回しにした結果、**カルテの保存期間を過ぎて取れなくなる**という最悪の展開が起こります。

